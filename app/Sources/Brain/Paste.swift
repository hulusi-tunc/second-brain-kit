import AppKit
import ApplicationServices
import Carbon

/// Puts text where the cursor is: clipboard, Cmd+V, then the old clipboard back.
enum Paste {
  static func trusted(prompt: Bool) -> Bool {
    let key = kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String
    return AXIsProcessTrustedWithOptions([key: prompt] as CFDictionary)
  }

  static let nowhere: Set<String> = ["com.apple.UserNotificationCenter", "com.apple.notificationcenterui", "com.apple.dock",
                                     "com.apple.loginwindow", "com.apple.systemuiserver", "com.apple.controlcenter", "com.apple.WindowManager"]

  enum Outcome { case pasted, held(String) }

  static func deliver(_ text: String) -> Outcome {
    let front = NSWorkspace.shared.frontmostApplication?.bundleIdentifier ?? ""
    if nowhere.contains(front) || IsSecureEventInputEnabled() {
      return .held(IsSecureEventInputEnabled() ? "secure input is on" : "no place to type")
    }
    type(text)
    return .pasted
  }

  /// Copy on purpose, from the notch's button: this one stays.
  static func copy(_ text: String) {
    let pb = NSPasteboard.general
    pb.clearContents(); pb.setString(text, forType: .string)
  }

  static func type(_ text: String) {
    let pb = NSPasteboard.general
    let saved: [(NSPasteboard.PasteboardType, Data)] = (pb.pasteboardItems ?? []).flatMap { item in
      item.types.compactMap { t in item.data(forType: t).map { (t, $0) } }
    }
    pb.clearContents()
    // marked as passing through, so clipboard history apps (Raycast, Paste, Maccy) skip it
    let item = NSPasteboardItem()
    item.setString(text, forType: .string)
    item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
    item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
    pb.writeObjects([item])
    let ours = pb.changeCount

    let src = CGEventSource(stateID: .combinedSessionState)
    let v: CGKeyCode = 9
    let down = CGEvent(keyboardEventSource: src, virtualKey: v, keyDown: true)
    let up = CGEvent(keyboardEventSource: src, virtualKey: v, keyDown: false)
    down?.flags = .maskCommand
    up?.flags = .maskCommand
    down?.post(tap: .cghidEventTap)
    up?.post(tap: .cghidEventTap)

    DispatchQueue.main.asyncAfter(deadline: .now() + 1.5) {
      guard pb.changeCount == ours else { return }
      pb.clearContents()
      guard !saved.isEmpty else { return }
      let item = NSPasteboardItem()
      for (t, d) in saved { item.setData(d, forType: t) }
      pb.writeObjects([item])
    }
  }
}
